    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
     try {

        String codigo = jTextField1.getText();
        String nombre = jTextField2.getText();
        String cargo = jTextField3.getText();
        
        if (!codigo.startsWith("E")) {

                JOptionPane.showMessageDialog(
            this,
            "El código debe comenzar con E"
        );

         return;
    }
        if (codigo.length() < 3) {

               JOptionPane.showMessageDialog(
            this,
            "El código debe tener al menos 3 caracteres"
        );

        return;
    }

        if (codigo.isBlank() || nombre.isBlank() || cargo.isBlank()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios");
            return;
        }

        Empleado empleado = new Empleado(codigo, nombre, cargo);

        EmpleadoDAOImpl dao = new EmpleadoDAOImpl();
        
        if (dao.existeCodigo(codigo)) {

                JOptionPane.showMessageDialog(
            this,
            "Ese código ya está registrado"
        );

        return;
    }

        dao.guardar(empleado);

        JOptionPane.showMessageDialog(this, "Empleado guardado correctamente");

        limpiar();

    } catch (DAOException error) {

        JOptionPane.showMessageDialog(this, error.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

