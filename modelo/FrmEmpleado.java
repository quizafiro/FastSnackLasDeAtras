    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
      try {

        String codigo = jTextField1.getText();

        if (codigo.isBlank()) {
            JOptionPane.showMessageDialog(this, "Ingresa el código");
            return;
        }

        EmpleadoDAOImpl dao = new EmpleadoDAOImpl();

        Optional<Empleado> emp = dao.findByCodigo(codigo);

        if (emp.isPresent()) {

            Empleado e = emp.get();

            jTextField1.setText(e.getCodigo());
            jTextField2.setText(e.getNombre());
            jTextField3.setText(e.getCargo());

            JOptionPane.showMessageDialog(this, "Empleado encontrado");

        } else {
            JOptionPane.showMessageDialog(this, "No encontrado");
        }

    } catch (DAOException error) {
        JOptionPane.showMessageDialog(this, error.getMessage());
    }
    }//GEN-LAST:event_jButton4ActionPerformed

